ROOT = Path(__file__).resolve().parents[3]
RECORDS = ROOT / ".dev/records/dispatches"
REVIEW_JOBS = (
    "check-tests", "security-audit", "adversarial-review", "adjudicate", "sweep"
)
DISPOSITIONS = ("open", "fixed", "addressed", "deferred", "ruled", "fix-round", "opinion")
CITATION = re.compile(
    r"contract item (?P<item>[1-9][0-9]*) of (?P<path>[^\s:;,]+)"
)
RECORD_ID = re.compile(
    r"^\d{8}T\d{6}Z-[a-z-]+-[a-z]+-[0-9a-f]{6}$"
)
SCOPE_REFERENCE = re.compile(
    r"numbered Contract items of (?P<path>[^\s:;,]+)"
)
COLUMNS = ("key", "record", "job", "stage", "harness", "model", "unit", "ref", "verdict",
           "n", "severity", "where", "claim", "reproduce", "disposition", "evidence", "disposed_at", "disposed_by")
SCHEMA = """
CREATE TABLE IF NOT EXISTS findings (
    key TEXT PRIMARY KEY, record TEXT NOT NULL, job TEXT, stage TEXT, harness TEXT, model TEXT,
    unit TEXT, ref TEXT, verdict TEXT, n INTEGER, severity TEXT, "where" TEXT, claim TEXT, reproduce TEXT,
    disposition TEXT NOT NULL DEFAULT 'open', evidence TEXT, disposed_at TEXT, disposed_by TEXT
)
"""
CALIBRATION_SCHEMA = """
CREATE TABLE IF NOT EXISTS calibration (
    calibration_key TEXT PRIMARY KEY, record TEXT NOT NULL, app TEXT NOT NULL,
    fault_id TEXT, finding_key TEXT, class TEXT NOT NULL, harness TEXT NOT NULL,
    model TEXT NOT NULL, claim TEXT NOT NULL
)
"""
CALIBRATION_CLASSES = ("caught", "missed", "false-positive", "unmatched", "unlocated")
CALIBRATION_COLUMNS = ("record", "app", "fault_id", "finding_key", "class", "harness", "model", "claim")


def database_path():
    return state_dir() / "findings.db"


def parse_citation(evidence):
    if not isinstance(evidence, str):
        return None
    return CITATION.search(evidence)


def citation_holds(evidence, root, scope_path):
    match = parse_citation(evidence)
    if match is None:
        return False, "evidence has no contract item N of PATH citation"

    root = Path(root).resolve()
    cited = Path(match.group("path"))
    scope = Path(scope_path)
    cited = (cited if cited.is_absolute() else root / cited).resolve()
    scope = (scope if scope.is_absolute() else root / scope).resolve()
    try:
        cited.relative_to(root)
        scope.relative_to(root)
    except ValueError:
        return False, "cited scope path is outside the repository root"
    if cited != scope:
        return False, "citation does not name the correction scope file"
    if not cited.is_file():
        return False, f"cited scope file {match.group('path')} is absent"
    try:
        body = cited.read_text(encoding="utf-8")
    except OSError as error:
        return False, f"cited scope file is unreadable: {error}"
    item = match.group("item")
    if re.search(rf"(?m)^\s*{re.escape(item)}\.\s", body) is None:
        return False, f"contract item {item} is absent from the cited scope file"
    return True, "citation holds"


def _unique_scope(paths, root):
    """The one work order the given files name, or None: a scope file a
    sentence references by "numbered Contract items of PATH", else a lone
    `scope-*.md` carrying numbered items."""
    referenced = []
    for path in paths:
        try:
            match = SCOPE_REFERENCE.search(path.read_text(encoding="utf-8"))
        except OSError:
            continue
        if match is None:
            continue
        candidate = (root / match.group("path")).resolve()
        try:
            candidate.relative_to(root)
        except ValueError:
            continue
        if candidate.is_file() and candidate not in referenced:
            referenced.append(candidate)
    if len(referenced) == 1:
        return str(referenced[0].relative_to(root))

    candidates = [
        path for path in paths
        if path.name.startswith("scope-")
        and not path.name.endswith(".scope.md")
        and path.name != "scope-discipline.md"
        and re.search(
            r"(?m)^\s*[1-9][0-9]*\.\s",
            path.read_text(encoding="utf-8"),
        )
    ]
    if len(candidates) == 1:
        return str(candidates[0].relative_to(root))
    return None


def work_order_scope(inputs, root):
    root = Path(root).resolve()
    shelf = root / ".dev" / "ladder-inputs"
    supplied = []
    for value in inputs:
        given = Path(value)
        candidates = (
            given if given.is_absolute() else root / given,
            shelf / given.name,
        )
        for candidate in candidates:
            try:
                resolved = candidate.resolve()
                resolved.relative_to(root)
            except ValueError:
                continue
            if resolved.is_file() and resolved not in supplied:
                supplied.append(resolved)

    # LD-24 (2026-09-11): the supplied inputs name the work order; the
    # shelf is swept only when they name none, because two work orders
    # on the shelf (scope-gate beside scope-item31) made the sweep find
    # two of everything and resolve nothing, for the cited read and the
    # correction gate alike.
    answer = _unique_scope(supplied, root)
    if answer is not None:
        return answer
    swept = list(supplied)
    if shelf.is_dir():
        for candidate in sorted(shelf.glob("scope-*.md")):
            resolved = candidate.resolve()
            try:
                resolved.relative_to(root)
            except ValueError:
                continue
            if resolved.is_file() and resolved not in swept:
                swept.append(resolved)
    return _unique_scope(swept, root)

def connect():
    path = database_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    connection.execute(SCHEMA)
    connection.execute(CALIBRATION_SCHEMA)
    connection.commit()
    return connection


def record_rows():
    for path in sorted(glob.glob(str(RECORDS / "*.json"))):
        rec = json.loads(Path(path).read_text(encoding="utf-8"))
        if rec.get("job") not in REVIEW_JOBS:
            continue
        env = ((rec.get("result") or {}).get("envelope") or {})
        for n, f in enumerate(env.get("findings") or [], 1):
            if not isinstance(f, dict):
                f = {"claim": str(f)}
            yield {
                "key": f"{rec['id']}#{n}", "record": rec["id"], "job": rec["job"], "stage": rec.get("stage"),
                "harness": (rec.get("harness") or {}).get("name"), "model": (rec.get("model") or {}).get("ran"),
                "unit": rec.get("unit"), "ref": ((rec.get("snapshot") or {}).get("ref_sha") or "")[:12],
                "verdict": env.get("verdict"), "n": n,
                "severity": ((f.get("severity") or f.get("priority") or "") or "").lower() or None,
                "where": f.get("where") or f.get("file") or None,
                "claim": f.get("claim") or f.get("finding") or f.get("title") or "",
                "reproduce": f.get("reproduce"),
            }


def do_import(argv):
    identity()
    if argv:
        refuse("arguments", "no arguments after import", " ".join(argv), "drop them")
    con = connect()
    n = 0
    for r in record_rows():
        con.execute(
            'INSERT INTO findings (key, record, job, stage, harness, model, unit, ref, verdict, n, severity, "where", claim, reproduce)'
            " VALUES (:key, :record, :job, :stage, :harness, :model, :unit, :ref, :verdict, :n, :severity, :where, :claim, :reproduce)"
            " ON CONFLICT(key) DO UPDATE SET record=excluded.record, job=excluded.job, stage=excluded.stage, harness=excluded.harness,"
            ' model=excluded.model, unit=excluded.unit, ref=excluded.ref, verdict=excluded.verdict, severity=excluded.severity,'
            ' "where"=excluded."where", claim=excluded.claim, reproduce=excluded.reproduce', r)
        n += 1
    con.commit()
    print(f"imported {n} finding(s) from {RECORDS}")
    return 0


def do_disposition(argv):
    agent = identity()
    if len(argv) != 3:
        refuse("arguments", "KEY DISPOSITION EVIDENCE", " ".join(argv) or "nothing", "pass exactly three arguments")
    key, what, why = argv
    if what not in DISPOSITIONS:
        refuse("disposition", "one of " + ", ".join(DISPOSITIONS), what, "choose a known disposition")
    con = connect()
    row = con.execute("SELECT key FROM findings WHERE key = ?", (key,)).fetchone()
    if row is None:
        refuse("key", "a finding key <record>#<n> held by the store", key, "run findings.py import first, or correct the key")
    con.execute("UPDATE findings SET disposition = ?, evidence = ?, disposed_at = ?, disposed_by = ? WHERE key = ?",
                (what, why, datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"), agent, key))
    con.commit()
    print(f"{key}\t{what}")
    return 0


def calibration_rows(raw):
    rows = []
    if not raw.strip():
        refuse("calibration", "one or more JSON objects on stdin", "empty stdin", "pipe grader JSONL")
    for n, line in enumerate(raw.splitlines(), 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as exc:
            refuse("calibration", "one JSON object per line", f"line {n}: {exc.msg}", "repair the grader output")
        required = ("record", "app", "class", "harness", "model", "claim")
        missing = [key for key in required if not isinstance(row.get(key), str) or not row[key]] if isinstance(row, dict) else list(required)
        optional = ("fault_id", "finding_key")
        invalid_optional = [key for key in optional if row.get(key) is not None and not isinstance(row.get(key), str)] if isinstance(row, dict) else []
        if missing or invalid_optional:
            bad = missing + invalid_optional
            refuse("calibration", "a complete grader row", f"line {n} invalid keys {bad}", "supply the calibration row contract")
        if row["class"] not in CALIBRATION_CLASSES:
            refuse("calibration", "class in " + ", ".join(CALIBRATION_CLASSES), repr(row["class"]), "choose a grading class")
        clean = {key: row.get(key) for key in CALIBRATION_COLUMNS}
        clean["calibration_key"] = json.dumps(
            [clean["record"], clean["app"], clean["fault_id"], clean["finding_key"]],
            separators=(",", ":"),
        )
        rows.append(clean)
    if not rows:
        refuse("calibration", "one or more JSON objects on stdin", "empty stdin", "pipe grader JSONL")
    return rows


def do_calibrate(argv):
    identity()
    if argv:
        refuse("arguments", "no arguments after calibrate", " ".join(argv), "drop them")
    rows = calibration_rows(sys.stdin.read())
    con = connect()
    for row in rows:
        con.execute(
            "INSERT INTO calibration (calibration_key, record, app, fault_id, finding_key, class, harness, model, claim)"
            " VALUES (:calibration_key, :record, :app, :fault_id, :finding_key, :class, :harness, :model, :claim)"
            " ON CONFLICT(calibration_key) DO UPDATE SET class=excluded.class, harness=excluded.harness,"
            " model=excluded.model, claim=excluded.claim",
            row,
        )
    con.commit()
    return 0


def do_export(argv):
    calibration = argv == ["--calibration"]
    # Triage 2026-09-11: `export` prints to stdout, which left the tracked
    # export unchanged after a disposition until someone redirected it;
    # `--write [PATH]` regenerates the file (default: the tracked export).
    write_to = None
    if argv[:1] == ["--write"]:
        if len(argv) > 2:
            refuse("arguments", "export --write [PATH]", " ".join(argv), "give at most one path")
        write_to = Path(argv[1]) if len(argv) == 2 else ROOT / "ops" / "conductor" / "findings" / "findings.jsonl"
        argv = []
    if argv and not calibration:
        refuse("arguments", "nothing, --calibration or --write [PATH] after export", " ".join(argv), "drop or correct it")
    con = connect()
    if write_to is not None:
        rows = [json.dumps({c: row[c] for c in COLUMNS}, sort_keys=True) + "\n"
                for row in con.execute("SELECT * FROM findings ORDER BY record, n")]
        write_to.parent.mkdir(parents=True, exist_ok=True)
        write_to.write_text("".join(rows), encoding="utf-8")
        print(f"wrote {len(rows)} row(s) to {write_to}")
        return 0
    if calibration:
        text = "".join(
            json.dumps({c: row[c] for c in CALIBRATION_COLUMNS}, sort_keys=True) + "\n"
            for row in con.execute(
                "SELECT * FROM calibration ORDER BY record, app, fault_id, finding_key"
            )
        )
        if text:
            destination = ROOT / "ops" / "conductor" / "findings" / "calibration.jsonl"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(text, encoding="utf-8")
        sys.stdout.write(text)
        return 0
    for row in con.execute("SELECT * FROM findings ORDER BY record, n"):
        sys.stdout.write(json.dumps({c: row[c] for c in COLUMNS}, sort_keys=True) + "\n")
    return 0


def do_summary(argv):
    if argv:
        refuse("arguments", "no arguments after summary", " ".join(argv), "drop them")
    con = connect()
    rows = [dict(r) for r in con.execute("SELECT * FROM findings")]
    print(f"findings={len(rows)} records={len({r['record'] for r in rows})}")
    by = Counter((r["unit"], r["job"], r["severity"]) for r in rows)
    for (unit, job, sev), n in sorted(by.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]), str(kv[0][2]))):
        print(f"{unit}\t{job}\t{sev}\t{n}")
    for k, n in sorted(Counter(r["disposition"] for r in rows).items()):
        print(f"disposition={k}\t{n}")
    return 0


def _record_scope(record):
    records = RECORDS.resolve()
    if RECORD_ID.fullmatch(record) is None:
        refuse(
            "key", "a finding row naming a dispatch record id",
            "a malformed record field", "repair the finding row or re-import it",
        )
    path = (records / f"{record}.json").resolve()
    try:
        path.relative_to(records)
    except ValueError:
        refuse(
            "key", "a finding record under the dispatch records directory",
            "the record path escapes that directory",
            "restore the record path or re-import the finding",
        )
    try:
        rec = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        rec = {}
    inputs = []
    for entry in ((rec.get("brief") or {}).get("inputs") or []):
        value = entry.get("path") if isinstance(entry, dict) else entry
        if isinstance(value, str):
            inputs.append(value)
    return work_order_scope(inputs, ROOT)


def do_cited(argv):
    if len(argv) != 1:
        refuse(
            "arguments", "one finding key after cited",
            " ".join(argv) or "nothing", "pass exactly one key",
        )
    key = argv[0]
    path = database_path()
    if not path.is_file():
        refuse("key", "a finding key held by the store", key, "run findings.py import first")
    con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row
    try:
        row = con.execute(
            "SELECT key, record, disposition, evidence FROM findings WHERE key = ?",
            (key,),
        ).fetchone()
    finally:
        con.close()
    if row is None:
        refuse("key", "a finding key held by the store", key, "run findings.py import first, or correct the key")
    if row["disposition"] == "open":
        print(f"{key}\topen")
        return 1

    scope_path = _record_scope(row["record"])
    parsed = parse_citation(row["evidence"])
    if parsed is not None:
        cited = Path(parsed.group("path"))
        cited = cited if cited.is_absolute() else ROOT / cited
        if not cited.exists():
            scope_path = parsed.group("path")
    if scope_path is None:
        ok, reason = False, "the finding record names no available scope file"
    else:
        ok, reason = citation_holds(row["evidence"], ROOT, scope_path)
    if not ok:
        print(f"{key}\tuncited: {reason}")
        return 1
    citation = parsed
    print(
        f"{key}\tcontract item {citation.group('item')} "
        f"of {citation.group('path')}"
    )
    return 0


VERBS = {
    "import": do_import,
    "disposition": do_disposition,
    "calibrate": do_calibrate,
    "export": do_export,
    "summary": do_summary,
    "cited": do_cited,
}


def main(argv):
    verb = argv[1] if len(argv) > 1 else None
    try:
        if verb not in VERBS:
            refuse("arguments", "one of " + ", ".join(VERBS), verb or "no verb", "name a verb")
        return VERBS[verb](argv[2:])
    except Refusal as exc:
        return emit(exc)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
