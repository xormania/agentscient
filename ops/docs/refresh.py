#!/usr/bin/env python3
"""Regenerate STATUS.md from live commands — never write it by hand.

    python3 ops/docs/refresh.py

Every figure on the page is produced at generation time; the page
stamps the commit it was generated at. Prose that runs nothing rots;
this page cannot.
"""

import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
REPO = DOCS.parents[1]


def run(*argv, label=None):
    # label names the TOOL, not the interpreter: a missing usage.py
    # must read "(unavailable: usage.py)", never "python3". A missing
    # binary raises rather than failing, so both paths are caught.
    label = label or argv[0]
    try:
        proc = subprocess.run(argv, capture_output=True, text=True,
                              cwd=REPO, check=False)
    except OSError:
        return f"(unavailable: {label})"
    if proc.returncode != 0:
        return f"(unavailable: {label})"
    return proc.stdout.strip()


def main() -> int:
    head = run("git", "rev-parse", "--short", "HEAD")
    branch = run("git", "rev-parse", "--abbrev-ref", "HEAD")
    prs = run("gh", "pr", "list", "--repo", "uscient/agentscient",
              "--json", "number,title,headRefName",
              "--template",
              "{{range .}}- #{{.number}} {{.title}} ({{.headRefName}})\n{{end}}")
    usage = run("python3", "ops/devlane/telemetry/usage.py", "report",
                "--repo", str(REPO), label="usage.py")
    todo_path = DOCS / "TODO.md"
    open_todos = sum(1 for line in todo_path.read_text().splitlines()
                     if line.startswith("- [ ]")) if todo_path.is_file() else 0
    (DOCS / "STATUS.md").write_text(f"""<!-- generated by refresh.py; do not edit by hand -->
# Dev-lane status

Generated at `{head}` (branch `{branch}`).

## Open pull requests

{prs or "- none"}

## Spend (usage.py report, this repo)

```
{usage}
```

## To-dos

{open_todos} open item(s) in [TODO.md](TODO.md).
""")
    print(f"STATUS.md regenerated at {head}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
